create table event (
    id bigint generated by default as identity primary key,
    name varchar(255) not null,
    start_at timestamp with time zone not null,
    duration_minutes integer not null check (duration_minutes >= 30),
    cost integer not null check (cost > 0),
    max_places integer not null check (max_places > 0),
    occupied_places integer not null check (occupied_places between 0 and max_places),
    status varchar(32) not null check (status in ('WAIT_START', 'STARTED', 'CANCELLED', 'FINISHED')),
    owner_id bigint not null references users(id),
    location_id bigint not null references location(id)
);

create index event_owner_idx on event (owner_id);
create index event_location_idx on event (location_id);
create index event_status_start_idx on event (status, start_at);
